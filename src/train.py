"""Grouped out-of-fold evaluation of the baseline and its ablations.

Run as `uv run python -m src.train`. Writes results/baseline_oof.json and the
OOF probabilities to data/oof_predictions.csv (derived from training data, so
kept out of git and regenerated by this script).
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score, roc_curve
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import Pipeline

from src.clean import load_clean_train
from src.features import SEED, build_pipeline
from src.groups import cv_group_key

ROOT = Path(__file__).resolve().parent.parent
N_FOLDS = 5
REPORTING_FPR = 0.01
# Ablation group (decision 2d): 257 rows after cleaning, all phishing.
ABLATION_GROUP = "duilawyeryork.com"
INPUT_VARIANTS = {"raw_url": False, "without_scheme_and_www": True}


def assign_folds(labels: pd.Series, groups: pd.Series) -> np.ndarray:
    """Fold id per row; every group lands in exactly one fold."""
    splitter = StratifiedGroupKFold(n_splits=N_FOLDS, shuffle=True, random_state=SEED)
    folds = np.empty(len(labels), dtype=int)
    for fold, (_, val_idx) in enumerate(splitter.split(labels, labels, groups)):
        folds[val_idx] = fold
    return folds


def oof_probabilities(
    urls: pd.Series, labels: pd.Series, folds: np.ndarray, strip: bool
) -> np.ndarray:
    """Phishing probability for each row from the model that did not see its fold."""
    probs = np.empty(len(urls))
    for fold in range(N_FOLDS):
        train, val = folds != fold, folds == fold
        model = build_pipeline(strip).fit(urls[train], labels[train])
        probs[val] = model.predict_proba(urls[val])[:, 1]
    return probs


def operating_point(
    labels: np.ndarray, probs: np.ndarray, max_fpr: float
) -> tuple[float, float, float]:
    """(threshold, tpr, fpr) with the highest TPR whose FPR does not exceed max_fpr.

    Rows with prob >= threshold are flagged. Values are unrounded.
    """
    fpr, tpr, thresholds = roc_curve(labels, probs)
    allowed = np.flatnonzero(fpr <= max_fpr)
    best = allowed[np.argmax(tpr[allowed])]
    return float(thresholds[best]), float(tpr[best]), float(fpr[best])


def recall_at_fpr(labels: np.ndarray, probs: np.ndarray, max_fpr: float) -> dict:
    """Highest recall whose FPR does not exceed max_fpr, with its threshold (rounded)."""
    threshold, tpr, fpr = operating_point(labels, probs, max_fpr)
    return {
        "max_fpr": max_fpr,
        "recall": round(tpr, 4),
        "fpr": round(fpr, 4),
        "threshold": round(threshold, 4),
    }


def summarize(labels: np.ndarray, probs: np.ndarray, folds: np.ndarray) -> dict:
    per_fold = [roc_auc_score(labels[folds == f], probs[folds == f]) for f in range(N_FOLDS)]
    return {
        "rows": int(labels.size),
        "phishing_rows": int(labels.sum()),
        "pooled_auc": round(float(roc_auc_score(labels, probs)), 4),
        "per_fold_auc": [round(float(a), 4) for a in per_fold],
        "per_fold_auc_std": round(float(np.std(per_fold)), 4),
        "recall_at_fpr": recall_at_fpr(labels, probs, REPORTING_FPR),
    }


def top_ngrams(model: Pipeline, n: int = 20) -> dict:
    """Largest positive (phishing) and negative (clean) coefficients."""
    names = model.named_steps["tfidf"].get_feature_names_out()
    coef = model.named_steps["clf"].coef_[0]
    order = np.argsort(coef)
    return {
        "phishing": [[names[i], round(float(coef[i]), 3)] for i in order[::-1][:n]],
        "clean": [[names[i], round(float(coef[i]), 3)] for i in order[:n]],
    }


def run_ablations(df: pd.DataFrame) -> tuple[dict, pd.DataFrame]:
    """OOF metrics for each input variant on all groups and without ABLATION_GROUP."""
    subsets = {"all_groups": df, "without_duilawyeryork": df[df["group"] != ABLATION_GROUP]}
    folds = {name: assign_folds(s["label"], s["group"]) for name, s in subsets.items()}
    results: dict = {}
    oof = df[["label", "group"]].assign(fold=folds["all_groups"])
    for variant, strip in INPUT_VARIANTS.items():
        results[variant] = {}
        for name, subset in subsets.items():
            urls, labels = subset["url"].reset_index(drop=True), subset["label"].to_numpy()
            probs = oof_probabilities(urls, pd.Series(labels), folds[name], strip)
            results[variant][name] = summarize(labels, probs, folds[name])
            if name == "all_groups":
                oof[f"prob_{variant}"] = probs
                keep = (subset["group"] != ABLATION_GROUP).to_numpy()
                results[variant]["all_groups_scored_without_duilawyeryork"] = summarize(
                    labels[keep], probs[keep], folds[name][keep]
                )
        results[variant]["top_ngrams_full_fit"] = top_ngrams(
            build_pipeline(strip).fit(df["url"], df["label"])
        )
    return results, oof


def main() -> None:
    df = load_clean_train()
    df["group"] = df["url"].map(cv_group_key)
    results, oof = run_ablations(df)
    report = {
        "input": "data/train.csv after cleaning (ADR 0001)",
        "model": "char 3-5-gram TF-IDF (sublinear, lowercase=False) + LogisticRegression(C=1)",
        "hyperparameter_configs_tried": 1,
        "cv": f"StratifiedGroupKFold(n_splits={N_FOLDS}, shuffle=True, random_state={SEED})",
        "group_key": "platform-level (src.groups.cv_group_key, ADR 0002)",
        "reporting_fpr_note": "recall_at_fpr is a reporting point, not the operating threshold",
        "ablation_group": ABLATION_GROUP,
        "results": results,
    }
    out = ROOT / "results" / "baseline_oof.json"
    out.write_text(json.dumps(report, indent=2))
    oof.to_csv(ROOT / "data" / "oof_predictions.csv", index=False)
    print(f"wrote {out.relative_to(ROOT)} and data/oof_predictions.csv")


if __name__ == "__main__":
    main()
